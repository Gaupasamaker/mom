export const replaceTimeGreeting = (language: AppLanguage, message: string, hour: number) => {
  const next = hour < 12 ? t(language, 'greeting.morning') : hour < 18 ? t(language, 'greeting.afternoon') : t(language, 'greeting.evening');
  const current =
    language === 'es'
      ? /^(Buenos dias|Buenos días|Buenas tardes|Buenas noches)/
      : /^(Good morning|Good afternoon|Good evening)/;
  return message.replace(current, next);
};
