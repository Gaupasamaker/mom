export type TranslationKey = keyof typeof dictionaries.en;

export const normalizeLanguage = (language?: string | null): AppLanguage =>
  language?.toLowerCase().startsWith('es') ? 'es' : 'en';

export const getDeviceLanguage = (): AppLanguage => {
  const nav = globalThis.navigator as unknown as { language?: string; languages?: readonly string[] } | undefined;
  const locale = nav?.languages?.[0] ?? nav?.language ?? Intl.DateTimeFormat().resolvedOptions().locale;
  return normalizeLanguage(locale);
};

export const localeFor = (language: AppLanguage) => (language === 'es' ? 'es-ES' : 'en-US');

export const t = (language: AppLanguage, key: TranslationKey, params: Params = {}): string => {
  let text = String(dictionaries[language][key] ?? dictionaries.en[key] ?? key);
  Object.entries(params).forEach(([paramKey, value]) => {
    text = text.replaceAll(`{{${paramKey}}}`, value === undefined ? '' : String(value));
  });
  return text;
};

